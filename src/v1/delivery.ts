/* Бесплатная доставка (владелец 16.11.2026): «доставка бесплатная от 30 000 ₽; сумма – с учётом баллов, то есть
   уже после вычета баллов». Порог сравнивается с суммой к оплате деньгами: товары минус списанные баллы. Доставку
   по-прежнему везёт СДЭК, менеджер оформляет её после заказа; ниже порога – по тарифам службы. Поменять порог –
   одна константа: она же в корзине, оформлении, тексте менеджеру, карточке товара и странице «Доставка и оплата». */
export const FREE_DELIVERY_FROM = 30_000;

const rub = (n: number) => `${n.toLocaleString('ru-RU')} ₽`;

/** Доставка бесплатная, если к оплате (после списания баллов) от порога. */
export const isFreeDelivery = (payRub: number) => payRub >= FREE_DELIVERY_FROM;

/** Сколько добрать до бесплатной доставки (0 – уже бесплатно). */
export const toFreeDelivery = (payRub: number) => Math.max(0, FREE_DELIVERY_FROM - payRub);

/** Правило одной фразой – для страницы «Доставка и оплата», карточки товара и оформления. */
export const FREE_DELIVERY_RULE = `Доставка бесплатная при заказе от ${rub(FREE_DELIVERY_FROM)}. Считается сумма к оплате после списания баллов.`;

export const FREE_DELIVERY_SHORT = `Бесплатная доставка от ${rub(FREE_DELIVERY_FROM)}`;
